// ---------- Справочники ----------

const FOOD_BY_ID = Object.fromEntries(FOODS.map(f => [f[0], f]));

function foodById(id) {
  return FOOD_BY_ID[id] || null;
}

function norm(s) {
  return String(s).toLowerCase().replace(/ё/g, 'е').replace(/[.,]/g, '');
}

// Поиск по названию и псевдонимам
function searchFoods(query, limit = 30) {
  const q = norm(query.trim());
  if (!q) return FOODS.slice(0, limit);
  const starts = [], contains = [];
  for (const f of FOODS) {
    if (norm(f[1]).startsWith(q)) starts.push(f);
    else if (norm(f[1]).includes(q) || f[2].some(a => norm(a).includes(q))) contains.push(f);
  }
  return [...starts, ...contains].slice(0, limit);
}

function foodsByCat(cat) {
  return FOODS.filter(f => f[4] === cat);
}

function calcMacros(food, grams) {
  const k = grams / 100;
  return {
    kcal: Math.round(food[4] * k),
    p: round1(food[5] * k),
    f: round1(food[6] * k),
    c: round1(food[7] * k),
  };
}

function round1(x) { return Math.round(x * 10) / 10; }

